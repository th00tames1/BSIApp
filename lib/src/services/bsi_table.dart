    for (var i = 1; i < dbhCm.length; i++) {
      if ((dbhCm[i] - dbh).abs() < (dbhCm[best] - dbh).abs()) best = i;
    }
    return percent[b - minBsi][best];
  }

  static bool isCut(int percent) => percent >= cutThresholdPercent;
