  /// 표에서 가장 가까운 칸의 고사 확률(%). 표 범위를 벗어나면 null.
  static int? lookup(double bsi, double dbh) {
    if (bsi.isNaN || dbh.isNaN) return null;
    final b = bsi.round();
    if (b < minBsi || b > maxBsi) return null;
    if (dbh < dbhCm.first - 1 || dbh > dbhCm.last + 1) return null;
